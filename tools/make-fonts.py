#!/usr/bin/env python3
"""Rasterise the display fonts into glyph tables for the firmware.

Each font becomes a table of glyphs (advance, offset from the pen
position on the baseline, size) and one blob of 4-bit coverage values,
two pixels per byte, row-major, glyph after glyph. The firmware blends
them onto the RGB565 frame (the LCD) or thresholds them (the OLED).

Fonts (OFL, in tools/fonts): Space Grotesk, JetBrains Mono, Inter; the
same faces as the web UI.

Run from the repo root: python3 tools/make-fonts.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "tools/fonts"
OUT = ROOT / "firmware/warpaxe/src/gfx"

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
EXTRA = "äöüÄÖÜß°·≈€…–"
TEXT = ASCII + EXTRA
DIGITS = "0123456789.,-–: "

# name, file, size px, axes (weight or [opsz, weight]), characters
FONTS = [
    ("HERO", "SpaceGrotesk.ttf", 38, [700], DIGITS),
    ("TITLE", "SpaceGrotesk.ttf", 26, [700], "ABCDEFGHIJKLMNOPQRSTUVWXYZÄÖÜ0123456789 .,-!:%"),
    ("VAL16", "JetBrainsMono.ttf", 16, [700], DIGITS + "/%"),
    ("VAL12", "JetBrainsMono.ttf", 12, [700], TEXT),
    ("MONO9", "JetBrainsMono.ttf", 9, [500], TEXT),
    ("LABEL9", "Inter.ttf", 9, [14, 500], TEXT),
    ("LABEL10", "Inter.ttf", 10, [14, 600], TEXT),
    ("UNIT13", "Inter.ttf", 13, [14, 500], TEXT),
    ("OLED24", "SpaceGrotesk.ttf", 24, [700], "0123456789.-"),
]


def raster(font, ch):
    pad = font.size
    w = int(font.getlength(ch)) + 2 * pad
    h = 3 * pad
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((pad, 2 * pad), ch, font=font, fill=255, anchor="ls")
    box = im.getbbox()
    # Advance in 1/16 px: the firmware adds them up unrounded, as a
    # browser does, so small text keeps its spacing.
    adv = round(font.getlength(ch) * 16)
    if ch == " ":
        # Hinting widens the glyphs at 9-10 px, the space does not grow
        # with them: keep a word gap of at least 0.36 em.
        adv = max(adv, round(font.size * 0.36 * 16))
    if not box:
        return adv, 0, 0, 0, 0, b""
    g = im.crop(box)
    return adv, box[0] - pad, box[1] - 2 * pad, g.width, g.height, g.tobytes()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rs = [
        "//! Generated by tools/make-fonts.py from Space Grotesk, JetBrains Mono",
        "//! and Inter (SIL Open Font License, tools/fonts). Do not edit.",
        "",
        "use super::font::{Font, Glyph};",
        "",
    ]
    total = 0
    for name, file, size, axes, chars in FONTS:
        font = ImageFont.truetype(str(TTF / file), size)
        font.set_variation_by_axes(axes)
        glyphs, nibbles = [], []
        for ch in sorted(set(chars)):
            adv, dx, dy, w, h, px = raster(font, ch)
            glyphs.append((ch, adv, dx, dy, w, h, len(nibbles)))
            nibbles.extend(round(v * 15 / 255) for v in px)
        if len(nibbles) % 2:
            nibbles.append(0)
        blob = bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        fname = f"{name.lower()}.a4"
        (OUT / "fonts").mkdir(exist_ok=True)
        (OUT / "fonts" / fname).write_bytes(blob)
        total += len(blob)
        rs.append(f"pub static {name}: Font = Font {{")
        rs.append(f'    data: include_bytes!("fonts/{fname}"),')
        rs.append("    glyphs: &[")
        for ch, adv, dx, dy, w, h, off in glyphs:
            rs.append(f"        Glyph {{ c: {ch!r}, adv: {adv}, dx: {dx}, dy: {dy}, w: {w}, h: {h}, off: {off} }},".replace("c: '\\\\'", "c: '\\\\'").replace("c: \"'\"", "c: '\\''"))
        rs.append("    ],")
        rs.append("};")
        rs.append("")
    (OUT / "fonts.rs").write_text("\n".join(rs))
    print(f"{len(FONTS)} fonts, {total} bytes of glyph data")


if __name__ == "__main__":
    main()
