#!/usr/bin/env python3
"""Put the translations into the firmware.

Sources (reviewed by native speakers before they land here):
  firmware/warpaxe/i18n/ui/<lang>.json       web UI, same keys as the English
                                              table in ui/index.html
  firmware/warpaxe/i18n/display/<lang>.json  device display, English text ->
                                              translation (Latin script only)

Writes the web-UI tables between the markers in ui/index.html and
firmware/warpaxe/src/display_i18n.rs. English and German stay inline where
they are. Checks key parity and placeholders; refuses on a mismatch.

Run from the repo root: python3 tools/i18n-apply.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FW = ROOT / "firmware/warpaxe"
UI = FW / "src/ui/index.html"
I18N = FW / "i18n"
START, END = "/* i18n:generated:start */", "/* i18n:generated:end */"
PH = re.compile(r"\{\w+\}")


def english_table(html):
    i = html.index("\nen: {")
    j = html.index("\nde: {")
    return dict(re.findall(r'\b(\w+):"((?:[^"\\]|\\.)*)"', html[i:j]))


def check(lang, src, tr, what):
    errors = []
    if set(src) != set(tr):
        errors.append(f"{what} {lang}: keys differ: missing {sorted(set(src) - set(tr))[:5]}, extra {sorted(set(tr) - set(src))[:5]}")
    for k in src:
        if k in tr and sorted(PH.findall(src[k])) != sorted(PH.findall(tr[k])):
            errors.append(f"{what} {lang}: placeholders differ in {k!r}")
    return errors


def js_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    html = UI.read_text()
    en = english_table(html)
    errors, blocks = [], []
    for f in sorted((I18N / "ui").glob("*.json")):
        lang = f.stem
        tr = json.loads(f.read_text())
        errors += check(lang, en, tr, "ui")
        body = ", ".join(f"{k}:{js_str(tr[k])}" for k in en if k in tr)
        blocks.append(f"{lang}: {{{body}}},")
    display_en = json.loads((I18N / "display/en_de.json").read_text())
    tables = []
    for f in sorted((I18N / "display").glob("*.json")):
        if f.stem == "en_de":
            continue
        tr = json.loads(f.read_text())
        errors += check(f.stem, display_en, tr, "display")
        rows = "\n".join(f"    ({js_str(k)}, {js_str(tr[k])})," for k in sorted(tr))
        tables.append((f.stem, rows))
    if errors:
        print("\n".join(errors))
        sys.exit(1)

    a, b = html.index(START) + len(START), html.index(END)
    html = html[:a] + "\n" + "\n".join(blocks) + "\n" + html[b:]
    UI.write_text(html)

    rs = [
        "//! Generated by tools/i18n-apply.py from firmware/warpaxe/i18n/display.",
        "//! Do not edit; English and German are inline in screens.rs.",
        "",
    ]
    for lang, rows in tables:
        rs.append(f"static {lang.upper()}: &[(&str, &str)] = &[\n{rows}\n];")
        rs.append("")
    arms = "\n".join(f'        "{lang}" => {lang.upper()},' for lang, _ in tables)
    rs.append(
        "/// The translation of an English display text, if the language has one.\n"
        "pub fn lookup(lang: &str, en: &str) -> Option<&'static str> {\n"
        "    let table: &[(&str, &str)] = match lang {\n"
        f"{arms}\n"
        "        _ => return None,\n"
        "    };\n"
        "    table\n"
        "        .binary_search_by(|(k, _)| (*k).cmp(en))\n"
        "        .ok()\n"
        "        .map(|i| table[i].1)\n"
        "}\n"
    )
    (FW / "src/display_i18n.rs").write_text("\n".join(rs))
    print(f"web UI: {len(blocks)} languages; display: {len(tables)} languages")


if __name__ == "__main__":
    main()
